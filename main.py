"""Partner ticket -> triage card JSON. Runs the model x prompt x sampling matrix and scores it.

    python main.py            # run the full matrix from config.toml, then write metrics
    python main.py report     # recompute metrics from results/runs/*.jsonl without calling models
    python main.py regress    # production config on the golden set; exit 1 below the threshold
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from dotenv import load_dotenv

from extractor.metrics import summarize, to_markdown
from extractor.pipeline import ResponseCache, extract, load_prompt
from extractor.providers import ProviderUnavailable, Sampling, build_provider

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
RUNS_DIR = ROOT / "results" / "runs"


def load_config() -> dict:
    return tomllib.loads((ROOT / "config.toml").read_text())


def load_texts() -> dict[str, str]:
    return {p.stem: p.read_text(encoding="utf-8") for p in sorted((DATA / "tickets").glob("*.txt"))}


def load_golden() -> dict:
    return json.loads((DATA / "golden.json").read_text(encoding="utf-8"))


def load_holdout() -> dict:
    return json.loads((DATA / "holdout.json").read_text(encoding="utf-8"))


def run_file(model: str, prompt_version: str, sampling: str) -> Path:
    return RUNS_DIR / f"{model}__{prompt_version}__{sampling}.jsonl"


def run_one(cfg, model_key, prompt_version, sampling_name, texts, cache, workers) -> list[dict] | None:
    mcfg = cfg["models"][model_key]
    provider = build_provider(mcfg, cfg["providers"])
    try:
        provider.check_available()
    except ProviderUnavailable as e:
        print(f"  skip {model_key}: {e}")
        return None
    s = cfg["sampling"][sampling_name]
    sampling = Sampling(sampling_name, s["temperature"], s["top_p"])
    prompt = load_prompt(prompt_version)
    prices = (mcfg["price_input"], mcfg["price_output"])
    # A local model on a laptop serves one request at a time; parallel calls would only distort latency.
    n_workers = 1 if mcfg["provider"] == "ollama" else workers

    def job(item):
        doc_id, text = item
        return extract(doc_id, text, provider, model_key, prices, prompt, sampling, cache)

    with ThreadPoolExecutor(n_workers) as pool:
        records = list(pool.map(job, texts.items()))
    return records


def write_metrics() -> list[dict]:
    texts, golden, holdout = load_texts(), load_golden(), load_holdout()
    rows = []
    for path in sorted(RUNS_DIR.glob("*.jsonl")):
        records = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
        if records:
            rows.append(summarize(records, golden, texts, holdout))
    rows.sort(key=lambda r: (r["model"], r["prompt_version"], r["sampling"]))
    out = ROOT / "results"
    (out / "metrics.json").write_text(json.dumps(rows, indent=2))
    (out / "metrics.md").write_text("# Metrics (generated by `python main.py report`)\n\n" + to_markdown(rows))
    return rows


def cmd_run(args, cfg) -> int:
    texts = load_texts()
    cache = ResponseCache(enabled=not args.no_cache)
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    models = args.models or cfg["run"]["models"]
    prompts = args.prompts or cfg["run"]["prompt_versions"]
    samplings = args.sampling or cfg["run"]["sampling"]
    for model in models:
        try:
            build_provider(cfg["models"][model], cfg["providers"]).check_available()
        except ProviderUnavailable as e:
            print(f"> skip {model}: {e}")
            continue
        for pv in prompts:
            for sname in samplings:
                print(f"> {model} | prompt {pv} | sampling {sname} | {len(texts)} docs")
                records = run_one(cfg, model, pv, sname, texts, cache, args.workers)
                with run_file(model, pv, sname).open("w") as f:
                    for r in records:
                        f.write(json.dumps(r, ensure_ascii=False) + "\n")
                statuses = [r["status"] for r in records]
                print(f"  ok={statuses.count('ok')} repaired={statuses.count('repaired')} failed={statuses.count('failed')}")
    rows = write_metrics()
    print("\n" + to_markdown(rows))
    return 0


def cmd_report(args, cfg) -> int:
    print(to_markdown(write_metrics()))
    return 0


def cmd_regress(args, cfg) -> int:
    prod = cfg["run"]["production"]
    golden = load_golden()
    texts = {k: v for k, v in load_texts().items() if k in golden}
    cache = ResponseCache(enabled=not args.no_cache)
    records = run_one(cfg, prod["model"], prod["prompt_version"], prod["sampling"], texts, cache, args.workers)
    if records is None:
        return 2
    m = summarize(records, golden, texts)
    threshold = cfg["run"]["regression_min_field_accuracy"]
    print(f"{prod} -> field accuracy {m['field_accuracy']:.1%}, valid {m['valid_final_pct']:.0f}%, "
          f"invented IDs {m['invented_ids']} (threshold {threshold:.0%})")
    for f, acc in m["field_accuracy_by_field"].items():
        print(f"  {f:<18} {acc:.0%}")
    ok = m["field_accuracy"] >= threshold and m["failed"] == 0 and m["invented_ids"] == 0
    print("PASS" if ok else "FAIL")
    return 0 if ok else 1


def main() -> int:
    load_dotenv(ROOT / ".env")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", nargs="?", default="run", choices=["run", "report", "regress"])
    ap.add_argument("--models", nargs="+", help="subset of models from config.toml")
    ap.add_argument("--prompts", nargs="+", help="subset of prompt versions")
    ap.add_argument("--sampling", nargs="+", help="subset of sampling configs")
    ap.add_argument("--no-cache", action="store_true", help="always call the model")
    ap.add_argument("--workers", type=int, default=4, help="parallel requests for hosted models")
    args = ap.parse_args()
    cfg = load_config()
    return {"run": cmd_run, "report": cmd_report, "regress": cmd_regress}[args.command](args, cfg)


if __name__ == "__main__":
    sys.exit(main())
